-- Esquema inicial, igual al que generaba Hibernate con ddl-auto=update.
-- Desde aquí los cambios de esquema van en migraciones nuevas (V2__..., V3__...), nunca editando esta.
-- Compatible con PostgreSQL y con H2 en modo PostgreSQL (perfil local).

CREATE TABLE vehicles (
    plate               VARCHAR(12) NOT NULL,
    vehicle_type        VARCHAR(20) NOT NULL,
    accumulated_minutes BIGINT      NOT NULL,
    version             BIGINT      NOT NULL,
    CONSTRAINT vehicles_pkey PRIMARY KEY (plate),
    CONSTRAINT vehicles_vehicle_type_check CHECK (vehicle_type IN ('OFICIAL', 'RESIDENTE', 'NO_RESIDENTE'))
);

CREATE TABLE parking_stays (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    vehicle_plate    VARCHAR(12)    NOT NULL,
    entry_time       TIMESTAMP(6)   NOT NULL,
    exit_time        TIMESTAMP(6),
    duration_minutes BIGINT,
    amount           NUMERIC(12, 2),
    CONSTRAINT parking_stays_pkey PRIMARY KEY (id),
    CONSTRAINT parking_stays_vehicle_fk FOREIGN KEY (vehicle_plate) REFERENCES vehicles (plate)
);

-- Entrada y salida buscan la estancia abierta de una placa; sin índice es un full scan que crece cada mes.
CREATE INDEX ix_parking_stays_plate_exit ON parking_stays (vehicle_plate, exit_time);
